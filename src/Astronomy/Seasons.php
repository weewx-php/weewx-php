    public static function _season_moment(float $year, int $which): float
    {
        $y = (($year - 2000.0) / 1000.0);
        [$a, $b, $c, $d, $e] = self::SEASON_MEANS[$which];
        $jde0 = (((($a + ($b * $y)) + ($c * ($y ** 2))) + ($d * ($y ** 3))) + ($e * ($y ** 4)));
        $t = (($jde0 - 2451545.0) / 36525.0);
        $w = deg2rad(((35999.373 * $t) - 2.47));
        $lam = ((1.0 + (0.0334 * cos($w))) + (0.0007 * cos((2 * $w))));
        $total = 0.0;
        foreach (self::SEASON_TERMS as [$size, $angle, $rate]) {
            $total += ($size * cos(deg2rad(($angle + ($rate * $t)))));
        }
        $jde = ($jde0 + ((1e-05 * $total) / $lam));
        return round(((($jde - 2440587.5) * 86400.0) - self::delta_t($year)));
    }

    public static function delta_t(float $year): float
    {
        if (($year < 2005)) {
            $t = ($year - 2000.0);
            return ((63.86 + (0.3345 * $t)) - (0.060374 * ($t ** 2)));
        }
        return (64.69 + (0.293 * ($year - 2005.0)));
    }

